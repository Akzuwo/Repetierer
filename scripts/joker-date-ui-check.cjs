const { ipcMain, app }=require('electron');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const Excel=require('exceljs');
const reader=require('../src/excelReader');
module.exports=async function check({win,evaluate,waitFor,shot,pause}) {
 const file=path.join(app.getPath('userData'),'Joker-Datum-Test.xlsx');
 const book=new Excel.Workbook(),sheet=book.addWorksheet('3a');sheet.getCell('A1').value='repetierer';sheet.getCell('A6').value='Testperson';sheet.getCell('H6').value=2;sheet.getCell('Q5').value='Joker Daten';sheet.getCell('Q6').value='01.09.2026; 02.09.2026';
 await book.xlsx.writeFile(file);await new Promise(resolve=>reader.init(file,resolve));const original=fs.readFileSync(file),plan=reader.getJokerDateMigrationStatus();
 let skipped=0;
 ipcMain.on('skip-joker-date-migration',()=>skipped++);
 ipcMain.on('run-joker-date-migration',(event,token)=>reader.migrate_joker_dates(token,result=>event.reply('joker-date-migration-result',result)));
 await evaluate(`require('./uiMotion').closeDialog(document.getElementById('ai-modal'))`);await pause(300);win.setSize(1100,800);await pause(100);
 const open=async()=>{win.webContents.send('joker-date-migration-required',plan,file);await waitFor(`document.getElementById('joker-date-migration-modal').classList.contains('modal-open')`);};
 await open();await shot('joker-date-migration-preview');
 assert.match(await evaluate(`document.getElementById('joker-date-migration-preview').textContent`),/6 Datumsspalten · 2 gespeicherte Joker-Daten/);
 await evaluate(`document.getElementById('joker-date-migration-skip').click()`);await pause(250);assert.equal(skipped,1);assert.deepEqual(fs.readFileSync(file),original);
 await open();const lock=path.join(path.dirname(file),'~$'+path.basename(file));fs.writeFileSync(lock,'fixture');
 assert.equal(await evaluate(`(()=>{document.getElementById('joker-date-migration-run').click();return document.getElementById('joker-date-migration-run').disabled;})()`),true);
 await waitFor(`document.getElementById('joker-date-migration-status').textContent.includes('gesperrt')`);await shot('joker-date-migration-locked');
 assert.deepEqual(fs.readFileSync(file),original);assert.equal(await evaluate(`document.getElementById('joker-date-migration-modal').classList.contains('modal-open')`),true);
 fs.unlinkSync(lock);
 await evaluate(`document.getElementById('joker-date-migration-run').click()`);
 await waitFor(`!document.getElementById('joker-date-migration-notice').classList.contains('update-hidden')`);
 assert.equal(reader.getJokerDateMigrationStatus().needsMigration,false);
 const updated=new Excel.Workbook();await updated.xlsx.readFile(file);assert.equal(updated.getWorksheet('3a').getCell('Q6').value,'01.09.2026');assert.equal(updated.getWorksheet('3a').getCell('R6').value,'02.09.2026');assert.equal(updated.getWorksheet('3a').getCell('H6').value,2);
 assert.match(await evaluate(`document.getElementById('joker-date-migration-notice').textContent`),/Sicherung:/);
 await shot('joker-date-migration-success');
 console.log('JOKER_DATE_UI_PASS: preview, skip, locked/retry, backup and real workbook conversion');
};
