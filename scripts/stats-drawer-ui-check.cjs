const assert = require('node:assert/strict');
const {ipcMain} = require('electron');
module.exports = async function({win, evaluate, waitFor, shot, pause}) {
	win.showInactive();
	await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', {features:[{name:'prefers-reduced-motion',value:'no-preference'}]});
	const click = id => evaluate(`document.getElementById(${JSON.stringify(id)}).click()`);
	const drawerDone = () => waitFor(`!document.getElementById('drawer').dataset.motionState`);
	const viewDone = () => waitFor(`!document.getElementById('drawer-content').dataset.viewMotion`);
	const header = await evaluate(`document.getElementById('title-bar').getBoundingClientRect().toJSON()`);
	await click('drawer-toggle');
	assert.equal(await evaluate(`document.getElementById('drawer').dataset.motionState`), 'opening');
	await pause(200);
	assert.equal(await evaluate(`document.getElementById('drawer').dataset.motionState`), 'opening', 'The opening has a soft settling phase');
	await drawerDone();
	assert.ok(await evaluate(`Math.abs(document.getElementById('drawer').getBoundingClientRect().left)<1`));
	assert.equal(await evaluate(`getComputedStyle(document.getElementById('content')).opacity`), '1', 'Content stays visible beneath the drawer');
	await click('drawer-data-view-btn');
	assert.equal(await evaluate(`document.getElementById('drawer-content').dataset.viewMotion`), 'exit');
	await viewDone();
	assert.equal(await evaluate(`document.getElementById('drawer-title').textContent`), 'Dateiverwaltung');
	assert.ok(await evaluate(`(()=>{const a=document.getElementById('drawer-back-btn').getBoundingClientRect(),b=document.getElementById('drawer-title').getBoundingClientRect(),c=document.getElementById('drawer-help-btn').getBoundingClientRect();return a.bottom<=b.top&&Math.abs(a.left-b.left)<1&&Math.abs((b.top+b.bottom-c.top-c.bottom)/2)<1})()`), 'Back arrow is above the title; help stays on the title line');
	await shot('drawer-file-management-liquid');
	// Interrupted submenu changes must commit only the latest intention.
	await click('drawer-back-btn'); await pause(35); await click('drawer-protocol-view-btn'); await viewDone();
	assert.equal(await evaluate(`document.getElementById('drawer-title').textContent`), 'Protokoll');
	await click('drawer-back-btn'); await viewDone();
	await click('drawer-toggle'); await pause(70); await click('drawer-toggle'); await drawerDone();
	assert.equal(await evaluate(`document.getElementById('drawer').inert`), false);
	await click('drawer-toggle'); await drawerDone();
	assert.ok(await evaluate(`document.getElementById('drawer').inert&&document.getElementById('drawer').getBoundingClientRect().right<0`));
	assert.deepEqual(await evaluate(`document.getElementById('title-bar').getBoundingClientRect().toJSON()`), header);

	const people = [{id:0,name:'Anna Beispiel'}, {id:1,name:'Max Beispiel'}];
	win.webContents.send('finished', false);
	win.webContents.send('teaching-session-started', {id:'timing',className:'Demo A',presentStudents:people,absentStudents:[],participationEntries:[],repetitionEntries:[]});
	await waitFor(`document.querySelectorAll('.participation-student').length===2&&!document.getElementById('content').dataset.pageMotion`);
	await click('session-repetition-tab');
	await waitFor(`!document.getElementById('content').dataset.pageMotion`);
	const starts = [], cancels = [];
	const onStart = (_e,token) => starts.push(token), onCancel = () => cancels.push(true);
	ipcMain.on('repetition-timing-start',onStart); ipcMain.on('repetition-timing-cancel',onCancel);
	win.webContents.send('ui-settings',{visualEffectsEnabled:true});
	win.webContents.send('name',['Anna Beispiel',false],people.map(p=>p.name),{...people[0],selectionToken:'first'});
	await waitFor(`document.querySelector('.selection-running')!==null`); await pause(150);
	assert.deepEqual(starts,[], 'Roulette is excluded from timing');
	await waitFor(`document.querySelector('.selection-running')===null`); await pause(60);
	assert.deepEqual(starts,['first']);
	await evaluate(`document.querySelector('#res button').click()`); await pause(60);
	assert.equal(cancels.length,1);
	win.webContents.send('name',['Anna Beispiel',false],people.map(p=>p.name),{...people[0],selectionToken:'reduced'});
	await waitFor(`document.querySelector('.selection-running')!==null`);
	await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]});
	await waitFor(`document.querySelector('.selection-running')===null`); await pause(60);
	assert.deepEqual(starts,['first','reduced'], 'Enabling reduced motion completes roulette and starts timing once');
	ipcMain.removeListener('repetition-timing-start',onStart); ipcMain.removeListener('repetition-timing-cancel',onCancel);
	await evaluate(`document.getElementById('stats-view-btn').classList.remove('disabled')`);
	await click('stats-view-btn');
	await waitFor(`document.getElementById('stats-list').getAttribute('aria-busy')==='true'`);
	const stats = Array.from({length:12},(_,i)=>({className:i?'Demo '+String.fromCharCode(65+i):'Demo A',personCount:25,repetitionsTotal:63,averageGrade:i===1?null:4.75,averageRepetitionsPerPerson:2.52,topRepetitionPerson:{name:'Anna Beispiel',repetitions:6},topRepetitionAdditionalCount:2,averageRepetitionDurationMs:i===1?null:152000,timedRepetitionsCount:i===1?0:9}));
	win.webContents.send('class-statistics-data',stats);
	await waitFor(`document.querySelectorAll('.stats-metric').length===48`);
	assert.equal(await evaluate(`document.querySelectorAll('.stats-class-detail:not(.update-hidden)').length`),1);
	assert.equal(await evaluate(`document.querySelector('.stats-class-detail:not(.update-hidden) .stats-metric:nth-child(3) strong').textContent`),'2:32');
	await shot('statistics-liquid-desktop');
	await evaluate(`document.getElementById('stats-class-select').value='Demo B';document.getElementById('stats-class-select').dispatchEvent(new Event('change'))`);
	assert.equal(await evaluate(`document.querySelector('.stats-class-detail:not(.update-hidden) .stats-metric strong').textContent`),'–');
	assert.equal(await evaluate(`document.querySelector('.stats-class-detail:not(.update-hidden) .stats-metric:nth-child(3) strong').textContent`),'–');
	await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'no-preference'}]});
	await evaluate(`document.getElementById('stats-class-select').value='Demo C';document.getElementById('stats-class-select').dispatchEvent(new Event('change'))`);
	assert.equal(await evaluate(`document.getElementById('content').dataset.pageMotion`),'exit');
	await waitFor(`!document.getElementById('content').dataset.pageMotion`);
	assert.equal(await evaluate(`document.querySelector('.stats-class-detail:not(.update-hidden) h3').textContent`),'Demo C');
	assert.equal(await evaluate(`window.selectRepetiererStatsClass('missing')`),false);
	win.setSize(390,680); await pause(200);
	const viewport = await evaluate(`(()=>{const e=document.getElementById('stats-list'),r=e.getBoundingClientRect();return {x:Math.round(r.left+r.width/2),y:Math.round(r.top+r.height/2),height:e.clientHeight,scroll:e.scrollHeight,right:r.right,bottom:r.bottom};})()`);
	assert.ok(viewport.height>100&&viewport.scroll>viewport.height&&viewport.right<=390&&viewport.bottom<=680,JSON.stringify(viewport));
	await shot('statistics-liquid-narrow');
	win.webContents.sendInputEvent({type:'mouseMove',x:viewport.x,y:viewport.y});
	win.webContents.sendInputEvent({type:'mouseWheel',x:viewport.x,y:viewport.y,deltaY:-300,deltaX:0,canScroll:true});
	await waitFor(`document.getElementById('stats-list').scrollTop>20`);
	assert.equal(await evaluate(`getComputedStyle(document.getElementById('stats-list')).scrollbarWidth`),'none');
	win.webContents.sendInputEvent({type:'mouseWheel',x:viewport.x,y:viewport.y,deltaY:500,deltaX:0,canScroll:true});
	await waitFor(`document.getElementById('stats-list').scrollTop===0`);
	assert.ok(await evaluate(`document.querySelector('.stats-class-heading').getBoundingClientRect().width<=innerWidth`));
	await click('drawer-toggle'); await drawerDone(); await click('drawer-data-view-btn'); await viewDone();
	assert.ok(await evaluate(`document.getElementById('drawer-title').scrollWidth<=document.getElementById('drawer-title').clientWidth`),'Submenu title fits the drawer');
	await shot('drawer-file-management-narrow');
	await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]});
	await click('drawer-back-btn'); await click('drawer-toggle');
	assert.equal(await evaluate(`document.getElementById('drawer').dataset.motionState`),undefined);
	assert.equal(await evaluate(`document.getElementById('drawer-content').dataset.viewMotion`),undefined);
	win.webContents.send('class-statistics-data',[]);
	await waitFor(`!document.getElementById('stats-empty').classList.contains('update-hidden')`);
	assert.equal(await evaluate(`document.getElementById('stats-class-picker').classList.contains('update-hidden')`),true);
	console.log('STATS_DRAWER_UI_PASS: attached liquid drawer, interrupted/submenu/reduced motion, back arrow layout, roulette timing IPC, class selection, unknown data, desktop/narrow, native wheel, hidden scrollbars');
};
