const assert = require('node:assert/strict');
const {ipcMain} = require('electron');
module.exports = async function({win,evaluate,waitFor,shot,pause}) {
  let saved = [];
  await evaluate(`document.getElementById('joker-date-migration-notice').classList.add('update-hidden')`);
  const onSave = (event,payload) => { saved.push(payload); event.reply('settings-saved',payload); };
  ipcMain.on('save-settings',onSave);
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'no-preference'}]});
  win.setSize(1100,800); await pause(200);
  win.showInactive();await waitFor(`document.visibilityState==='visible'`);
  const visibleViews = () => evaluate(`[...document.querySelector('#content').children].filter(e=>!e.classList.contains('update-hidden')).map(e=>e.id)`);
  const before = await visibleViews();
  const header = await evaluate(`(()=>{const r=document.getElementById('title-bar').getBoundingClientRect();return [r.x,r.y,r.width,r.height]})()`);
  await evaluate(`document.getElementById('settings-btn').click()`);
  await waitFor(`document.getElementById('content').dataset.pageMotion==='enter'`);
  const startY = await evaluate(`+require('./vendor/ui-motion.js').gsap.getProperty(document.getElementById('content'),'y')`);
  assert.ok(startY < 0,'Page enters from above');
  assert.deepEqual(await evaluate(`(()=>{const r=document.getElementById('title-bar').getBoundingClientRect();return [r.x,r.y,r.width,r.height]})()`),header,'Header remains fixed during the pop');
  await waitFor(`!document.getElementById('content').dataset.pageMotion`);
  assert.equal(await evaluate(`document.getElementById('settings-view').parentElement.id`),'content');
  assert.equal(await evaluate(`document.getElementById('settings-view').classList.contains('modal')`),false);
  assert.equal(await evaluate(`document.documentElement.dataset.crystalOverlay`),'false');
  assert.equal(await evaluate(`document.getElementById('settings-view').hasAttribute('data-glass')`),false,'Settings has no outer glass card');
  assert.deepEqual(await visibleViews(),['settings-view']);
  await shot('settings-page-desktop');
  const scroller = '#settings-view .settings-scroll-area';
  await evaluate(`document.querySelector(${JSON.stringify(scroller)}).scrollTop=500`);
  await pause(250);
  assert.ok(await evaluate(`document.querySelector(${JSON.stringify(scroller)}).scrollTop`)>100,'Settings scrolls');
  assert.equal(await evaluate(`getComputedStyle(document.querySelector(${JSON.stringify(scroller)})).scrollbarWidth`),'none');
  await evaluate(`document.getElementById('settings-help-btn').click()`);
  await waitFor(`document.getElementById('settings-help-modal').classList.contains('modal-open')`);
  await evaluate(`document.getElementById('close-settings-help-btn').click()`);
  await waitFor(`getComputedStyle(document.getElementById('settings-help-modal')).display==='none'`);
  assert.equal(await evaluate(`document.getElementById('settings-view').classList.contains('update-hidden')`),false);
  assert.ok(await evaluate(`document.querySelector(${JSON.stringify(scroller)}).scrollTop`)>100,'Help retains scroll position');
  await evaluate(`document.getElementById('probability-factor-setting').value='1.8';document.getElementById('never-selected-boost-factor-setting').value='1.5';document.getElementById('save-settings-btn').click()`);
  await waitFor(`document.getElementById('settings-view').classList.contains('update-hidden') && !document.getElementById('content').dataset.pageMotion`);
  assert.equal(saved.length,1);assert.equal(saved[0].probabilityDecreaseFactor,1.8);
  assert.deepEqual(await visibleViews(),before,'Save restores the previous page');
  for(const [w,h] of [[680,560],[390,844]]) {
    win.setSize(w,h);await pause(160);
    await evaluate(`document.getElementById('settings-btn').click()`);
    await waitFor(`!document.getElementById('settings-view').classList.contains('update-hidden') && !document.getElementById('content').dataset.pageMotion`);
    const bounds = await evaluate(`(()=>{const r=document.getElementById('settings-view').getBoundingClientRect(),b=document.getElementById('save-settings-btn').getBoundingClientRect();return r.left>=-1&&r.right<=innerWidth+1&&r.top>=0&&r.bottom<=innerHeight+1&&b.bottom<=innerHeight;})()`);
    assert.ok(bounds,'Page and save action stay within viewport '+w);
    await shot('settings-page-'+w);
    await evaluate(`document.getElementById('settings-back-btn').click()`);
    await waitFor(`document.getElementById('settings-view').classList.contains('update-hidden') && !document.getElementById('content').dataset.pageMotion`);
  }
  assert.equal(saved.length,1,'Back does not save changes');
  win.setSize(1100,800);
  await evaluate(`document.getElementById('settings-btn').click()`);
  await waitFor(`!document.getElementById('settings-view').classList.contains('update-hidden')`);
  await evaluate(`document.getElementById('assessment-nav-btn').click()`);
  await waitFor(`!document.getElementById('assessment-view').classList.contains('update-hidden') && !document.getElementById('content').dataset.pageMotion`);
  assert.equal(await evaluate(`document.getElementById('settings-view').classList.contains('update-hidden')`),true,'Direct navigation dismisses settings');
  await evaluate(`document.getElementById('repetition-nav-btn').click()`);
  await waitFor(`!document.getElementById('content').dataset.pageMotion`);
  ipcMain.removeListener('save-settings',onSave);
  console.log('SETTINGS_PAGE_UI_PASS: page, fixed header/top-down pop, help/scroll, save/back, desktop/compact/mobile, direct navigation');
};
