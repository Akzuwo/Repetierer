const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawn, spawnSync } = require('node:child_process');
const { AssessmentStore, DEFAULT_CRITERIA } = require('../src/assessment/assessmentStore');
const { AssessmentApiClient } = require('../src/assessment/assessmentApiClient');
const root = path.join(__dirname,'..');
const wrangler = path.join(root,'node_modules/wrangler/bin/wrangler.js');
const BASE = '/app/services/repetierer/';

test('Worker + echtes D1: Erstellung, Umfrage, parallele Duplikate, Sync, Schliessung, Löschung, Rechte und Aufbewahrung', {timeout:120000}, async t => {
  fs.mkdirSync(path.join(root,'.cloudflare-test'),{recursive:true});
  const directory = fs.mkdtempSync(path.join(root,'.cloudflare-test','e2e-'));
  const env = {...process.env, NODE_USE_SYSTEM_CA:'1', WRANGLER_SEND_METRICS:'false'};
  const token = 'rt_' + crypto.randomBytes(32).toString('base64url');
  const otherToken = 'rt_' + crypto.randomBytes(32).toString('base64url');
  const hash = x => crypto.createHash('sha256').update(x).digest('hex');
  const seed = path.join(directory,'seed.sql');
  const expiry = Date.now()+86400000;
  fs.writeFileSync(seed, `INSERT INTO teachers VALUES ('teacher-a','${hash(token)}','Test A',${expiry},NULL); INSERT INTO teachers VALUES ('teacher-b','${hash(otherToken)}','Test B',${expiry},NULL);`);
  const run = (...args) => {
    const result=spawnSync(process.execPath,[wrangler,...args,'--config','cloudflare/wrangler.jsonc','--persist-to',directory],{cwd:root,env,encoding:'utf8',windowsHide:true});
    assert.equal(result.status,0, result.stderr);
  };
  run('d1','migrations','apply','repetierer-assessment','--local');
  run('d1','execute','repetierer-assessment','--local','--file',seed);
  fs.unlinkSync(seed);
  const net = require('node:net');
  const port=await new Promise(resolve=>{const server=net.createServer();server.listen(0,'127.0.0.1',()=>{const p=server.address().port;server.close(()=>resolve(p));});});
  const server=spawn(process.execPath,[wrangler,'dev','--config','cloudflare/wrangler.jsonc','--local','--port',String(port),'--persist-to',directory,'--test-scheduled'],{cwd:root,env,windowsHide:true,stdio:['ignore','pipe','pipe']});
  let output=''; server.stdout.on('data',c=>output+=c);server.stderr.on('data',c=>output+=c);
  t.after(async()=>{fs.writeFileSync(path.join(directory,'worker.log'),output);server.kill(); await Promise.race([new Promise(resolve=>server.once('exit',resolve)),new Promise(resolve=>setTimeout(resolve,3000))]);});
  const origin='http://127.0.0.1:'+port;
  let ready=false;
  for(let i=0;i<150;i++) {try {if((await fetch(origin+BASE+'api/health')).ok){ready=true;break;}}catch{} await new Promise(r=>setTimeout(r,100));}
  assert.ok(ready,output);
  const client=new AssessmentApiClient({apiUrl:origin+BASE+'api',teacherToken:token});
  const other=new AssessmentApiClient({apiUrl:origin+BASE+'api',teacherToken:otherToken});
  await client.checkStatus();
  const students=[{id:0,name:'Anna Müller'},{id:1,name:'Max Muster'}];
  const workbook=path.join(directory,'class.xlsx');
  const dataPath=path.join(directory,'mitmachnoten.json');
  const store=new AssessmentStore(dataPath);
  const round=store.createRound(workbook,'3a',students,{title:'E2E Runde'});
  assert.match(round.externalRoundId,/^[a-f0-9-]{36}$/);
  await client.createRound(round,10);
  await client.createRound(round,10); // lost response/retry: same round
  const publicURL=origin+BASE+'api/public/rounds/'+round.externalRoundId;
  const page=await fetch(origin+BASE+'?round='+round.externalRoundId);
  assert.equal(page.status,200); assert.match(await page.text(),/Deine Selbstbeurteilung/);
  assert.match(page.headers.get('Content-Security-Policy'),/frame-ancestors 'none'/);
  const publicRound=await (await fetch(publicURL)).json();
  assert.equal(publicRound.round.criteria.length,DEFAULT_CRITERIA.length);
  assert.equal(JSON.stringify(publicRound).includes('Anna'),false);
  const answers=Object.fromEntries(DEFAULT_CRITERIA.map(c=>[c.id,4]));
  const payload={name:'Anna Müller',email:'anna@example.ch',browserToken:'a'.repeat(48),answers,additionalQuality:'Fachwissen',comment:'Test'};
  const send=(data,originHeader=origin)=>fetch(publicURL+'/responses',{method:'POST',headers:{'Content-Type':'application/json',Origin:originHeader},body:JSON.stringify(data)});
  assert.equal((await send({...payload,answers:{}})).status,400);
  assert.equal((await send(payload,'https://unrelated.example')).status,403);
  const simultaneous=await Promise.all(Array.from({length:8},(_,i)=>send({...payload,name:i%2?' ANNA   MÜLLER ':'Anna Mu\u0308ller',browserToken:String(i).repeat(48)})));
  assert.equal(simultaneous.filter(r=>r.status===201).length,1);
  assert.equal(simultaneous.filter(r=>r.status===409).length,7);
  const accepted=simultaneous.findIndex(r=>r.status===201);
  assert.equal((await send({...payload,name:'Max Muster',browserToken:String(accepted).repeat(48)})).status,409);
  assert.equal((await send({...payload,name:'Max Muster',browserToken:'b'.repeat(48),email:'max@example.ch'})).status,201);
  await assert.rejects(other.fetchResponses({externalRoundId:round.externalRoundId,criteria:round.criteria}),e=>e.code==='ASSESSMENT_ROUND_NOT_FOUND');
  assert.equal((await fetch(origin+BASE+'api/teacher/rounds/'+round.externalRoundId+'/responses')).status,401);
  const first=await client.fetchResponses({externalRoundId:round.externalRoundId,criteria:round.criteria});
  store.applyResponses(workbook,'3a',students,round.id,first.responses);
  store.applyResponses(workbook,'3a',students,round.id,first.responses);
  const reloaded=new AssessmentStore(dataPath);
  const saved=reloaded.getRound(workbook,'3a',students,round.id).round;
  assert.equal(saved.externalResponses.length,2);
  const next=await client.fetchResponses({externalRoundId:round.externalRoundId,criteria:round.criteria,knownResponseIds:saved.externalResponses.map(r=>r.externalResponseId)});
  assert.equal(next.responses.length,0);
  await client.closeRound(round.externalRoundId);
  await client.closeRound(round.externalRoundId);
  assert.equal((await send({...payload,name:'Weitere Person',browserToken:'c'.repeat(48)})).status,410);
  assert.equal((await client.fetchResponses({externalRoundId:round.externalRoundId,criteria:round.criteria})).responses.length,2);
  await client.deleteRound(round.externalRoundId);
  await client.deleteRound(round.externalRoundId);
  assert.equal((await fetch(publicURL)).status,404);
  if (process.env.REPETIERER_BACKEND_ONLY !== '1') {
  const credentialFile=path.join(directory,'teacher.env');
  fs.writeFileSync(credentialFile,`ASSESSMENT_TEACHER_TOKEN=${token}\n`,{mode:0o600});
  const controlFile=path.join(directory,'control.json');
  fs.writeFileSync(controlFile,JSON.stringify({directory,credentialFile,apiUrl:origin+BASE+'api'}));
  const electronEnv={...env};delete electronEnv.ELECTRON_RUN_AS_NODE;
  const ui=spawnSync(require('electron'),[path.join(root,'scripts/cloudflare-electron-e2e.js'),controlFile],{cwd:root,env:electronEnv,encoding:'utf8',windowsHide:true,timeout:60000});
  assert.equal(ui.status,0,ui.stderr+'\n'+ui.stdout);
  console.log(ui.stdout.trim());
  fs.unlinkSync(credentialFile);
  }
  const expired=crypto.randomUUID();
  const retention=path.join(directory,'retention.sql');
  fs.writeFileSync(retention,`INSERT INTO rounds (id,teacher_id,title,criteria,deadline,expires_at,created_at,max_responses) VALUES ('${expired}','teacher-a','Expired','[]',1,1,1,10); INSERT INTO responses (id,round_id,name,name_key,email,browser_hash,answers,additional_quality,comment,submitted_at) VALUES ('old','${expired}','Test','test','test@example.ch','hash','{}','','',1); UPDATE teachers SET revoked_at = 1 WHERE id = 'teacher-b';`);
  run('d1','execute','repetierer-assessment','--local','--file',retention);
  fs.unlinkSync(retention);
  for(let i=0;i<100;i++) {try {if((await fetch(origin+BASE+'api/health')).ok)break;}catch{} await new Promise(r=>setTimeout(r,100));}
  await assert.rejects(other.checkStatus(),e=>e.code==='ASSESSMENT_API_UNAUTHORIZED');
  assert.equal((await fetch(origin+'/__scheduled?cron=17+2+*+*+*')).status,200);
  const check=path.join(directory,'check.sql');
  fs.writeFileSync(check,"SELECT (SELECT COUNT(*) FROM rounds) AS rounds, (SELECT COUNT(*) FROM responses) AS responses;");
  const result=spawnSync(process.execPath,[wrangler,'d1','execute','repetierer-assessment','--local','--config','cloudflare/wrangler.jsonc','--persist-to',directory,'--file',check,'--json'],{cwd:root,env,encoding:'utf8',windowsHide:true});
  assert.equal(result.status,0,result.stderr);
  const rows=JSON.parse(result.stdout);
  assert.deepEqual(rows[0].results[0],{rounds:0,responses:0});
});
